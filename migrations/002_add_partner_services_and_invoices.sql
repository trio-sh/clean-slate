        )
    );

-- Policy: Partners can delete their depot's services
CREATE POLICY partner_services_delete_policy ON partner_services
    FOR DELETE
    USING (
        depot_id IN (
            SELECT depot_id FROM users WHERE id = auth.uid() AND role = 'partner'
        )

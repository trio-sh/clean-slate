-- ============================================
-- PARTNER SERVICES TABLE
-- ============================================
-- Partners can create and manage their own services with custom pricing
CREATE TABLE IF NOT EXISTS partner_services (
    id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
    depot_id UUID NOT NULL REFERENCES depots(id) ON DELETE CASCADE,
    name VARCHAR(200) NOT NULL,
    description TEXT,
    category VARCHAR(50) NOT NULL CHECK (category IN ('laundry', 'dry-cleaning', 'specialty')),
    price DECIMAL(10, 2) NOT NULL CHECK (price > 0),
    unit VARCHAR(20) NOT NULL CHECK (unit IN ('lb', 'item')),
    is_active BOOLEAN DEFAULT true,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- Create indexes for efficient querying
CREATE INDEX idx_partner_services_depot_id ON partner_services(depot_id);
CREATE INDEX idx_partner_services_category ON partner_services(category);
CREATE INDEX idx_partner_services_is_active ON partner_services(is_active);

-- Add RLS (Row Level Security) policies
ALTER TABLE partner_services ENABLE ROW LEVEL SECURITY;

-- Policy: Partners can view their own depot's services
CREATE POLICY partner_services_select_policy ON partner_services
    FOR SELECT
    USING (
        depot_id IN (
            SELECT depot_id FROM users WHERE id = auth.uid()
        )
    );

-- Policy: Partners can insert services for their depot
CREATE POLICY partner_services_insert_policy ON partner_services
    FOR INSERT
    WITH CHECK (
        depot_id IN (
            SELECT depot_id FROM users WHERE id = auth.uid() AND role = 'partner'
        )
